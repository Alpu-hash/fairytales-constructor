def reason(title, work_key=""):
    if work_key in MANUAL_WORKS:
        return MANUAL_WORKS[work_key]
    m = PAREN_RE.search(title.split("/")[0])
    if m and m.group(1).split(";")[0].strip() in ADULT_AUTHORS:
        return "взрослая литература (автор убран целиком)"
    for why, pref in PREFIXES:
        if title.startswith(pref):
            return why
    for seg in title.split("/"):
        if SEGMENT_RE.match(seg.strip().lower()):
            return "предисловие / примечания / загадки (служебный текст)"
    return None


def norm_key(s):
    return re.sub(r"[\W_]+", " ", s.lower().replace("ё", "е")).strip()


def base_of(title):
    return norm_key(re.sub(r"\s*\(.*?\)", "", title.split("/")[0]))


CHAPTER_RE = re.compile(r"^(глава|часть|\d+|[ivxlc]+)\b", re.I)


def fix_work_keys(rows):
    """В сборниках («Народные русские сказки (Афанасьев)/Кощей Бессмертный») prepare_corpus дал ВСЕМ сказкам сборника
    один work_key, и они целиком попадали в одну выборку. Здесь для сборников work_key берётся из названия сказки.
    Сборник = общий заголовок, у которого 4 и более разных подзаголовков, не являющихся номерами глав."""
    subs = collections.defaultdict(set)
    for r in rows:
        if "/" in r["title"]:
            sub = r["title"].split("/", 1)[1].strip()
            if sub and not CHAPTER_RE.match(sub):
                subs[base_of(r["title"])].add(norm_key(sub))
    collections_ = {b for b, v in subs.items() if len(v) >= 4}
    changed = 0
    for r in rows:
        b = base_of(r["title"])
        if b in collections_ and "/" in r["title"]:
            new = norm_key(r["title"].split("/", 1)[1])
            if new and new != r["work_key"]:
                r["work_key"] = new
                changed += 1
    return changed, sorted(collections_)


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    rows = [json.loads(l) for l in open(SRC, encoding="utf-8")]
    changed, colls = fix_work_keys(rows)
    print(f"work_key исправлен у {changed} текстов из сборников: {colls}")
    keep, gone = [], []
    for r in rows:
        why = reason(r["title"], r.get("work_key", ""))
        (gone if why else keep).append((r, why))
    with open(OUT, "w", encoding="utf-8") as f:
        for r, _ in keep:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open(REMOVED, "w", encoding="utf-8") as f:
        for r, why in gone:
            f.write(f"{r['id']}\t{r['title']}\t{r['n_words']}\t{why}\n")
    print(f"Было: {len(rows)}; убрано: {len(gone)}; осталось: {len(keep)}")
    words_gone = sum(r["n_words"] for r, _ in gone)
    print(f"Слов убрано: {words_gone}; осталось: {sum(r['n_words'] for r, _ in keep)}")
    for why, n in collections.Counter(w for _, w in gone).most_common():
        print(f"  {n:3d}  {why}")


if __name__ == "__main__":
    main()
